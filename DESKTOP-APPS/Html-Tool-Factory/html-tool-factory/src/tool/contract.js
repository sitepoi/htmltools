'use strict'

// The html-tool contract from html-tool-rules.txt, enforced in code.
// A generated tool is exactly three files plus a test harness:
//   app/<Tool>.html  body markup only, first line <!-- html build YYYY-MM-DD-N -->
//   app/<Tool>.css   rules only,     first line /* css build YYYY-MM-DD-N */
//   app/<Tool>.js    logic only,     first line /* js build YYYY-MM-DD-N */
// There is no index.html, no build step, no framework and no CDN.

const path = require('path')

const STAMP_PATTERN = /^(?:\d{4}-\d{2}-\d{2})-\d+$/

function todayStamp(date) {
  const value = date instanceof Date ? date : new Date()
  const year = value.getFullYear()
  const month = String(value.getMonth() + 1).padStart(2, '0')
  const day = String(value.getDate()).padStart(2, '0')
  return year + '-' + month + '-' + day
}

function buildStamp(date) {
  return todayStamp(date) + '-1'
}

function firstLineFor(kind, stamp) {
  if (kind === 'html') return '<!-- html build ' + stamp + ' -->'
  return '/* ' + kind + ' build ' + stamp + ' */'
}

function stampOf(kind, stamp) {
  const value = String(stamp || buildStamp())
  return STAMP_PATTERN.test(value) ? value : buildStamp()
}

const FORBIDDEN_EXTENSIONS = ['.jsx', '.tsx', '.ts', '.mjs', '.cjs', '.vue', '.svelte', '.scss', '.sass', '.less', '.map']

const FORBIDDEN_JS_APIS = [
  { pattern: /<script\b/i, message: 'The JavaScript file must not contain a <script> tag.' },
  { pattern: /<\/script\s*>/i, message: 'The JavaScript file must not contain a </script> sequence.' },
  { pattern: /document\.write\s*\(/i, message: 'document.write is not allowed.' },
  { pattern: /\b(?:window\.)?localStorage\b/, message: 'localStorage is not allowed inside a tool. Use the platform SDK.' },
  { pattern: /\b(?:window\.)?sessionStorage\b/, message: 'sessionStorage is not allowed inside a tool. Use the platform SDK.' },
  { pattern: /\bfetch\s*\(/i, message: 'fetch is not allowed inside a tool. Use the platform SDK (requestAI) instead.' },
  { pattern: /XMLHttpRequest/i, message: 'XMLHttpRequest is not allowed inside a tool. Use the platform SDK instead.' },
  { pattern: /\balert\s*\(/i, message: 'alert is not allowed inside a tool. Use an inline status message instead.' },
  { pattern: /DOMContentLoaded/, message: 'DOMContentLoaded is not allowed. Use tool.onReady.' },
  { pattern: /\brequire\s*\(\s*['"]/, message: 'require() is not allowed inside a tool. There is no build step.' },
  { pattern: /^\s*(?:import|export)\s/m, message: 'ES module import/export is not allowed inside a tool. There is no build step.' },
  { pattern: /\beval\s*\(/i, message: 'eval is not allowed inside a tool.' }
]

const FORBIDDEN_HTML = [
  { pattern: /<!DOCTYPE/i, message: 'The html file must not contain <!DOCTYPE>. It is a body fragment.' },
  { pattern: /<html\b/i, message: 'The html file must not contain <html>.' },
  { pattern: /<head\b/i, message: 'The html file must not contain <head>.' },
  { pattern: /<body\b/i, message: 'The html file must not contain <body>.' },
  { pattern: /<script\b/i, message: 'The html file must not contain <script>. Put logic in the .js file.' },
  { pattern: /<style\b/i, message: 'The html file must not contain <style>. Put rules in the .css file.' },
  { pattern: /<link\b/i, message: 'The html file must not contain <link>. The platform loads the .css file.' },
  { pattern: /<iframe\b/i, message: 'iframes are not allowed inside a tool.' }
]

function allowedToolPaths(toolName) {
  const name = String(toolName || '').trim()
  return [
    'app/' + name + '.html',
    'app/' + name + '.css',
    'app/' + name + '.js',
    'app/test-harness.html'
  ]
}

// Build tasks may only touch the three contract files, the harness and docs.
function checkTargetPath(relativePath, toolName) {
  const clean = String(relativePath || '').replace(/\\/g, '/').trim().replace(/^\.?\//, '')
  if (!clean) return { ok: false, reason: 'The path is empty.' }
  if (clean.split('/').includes('..')) return { ok: false, reason: 'The path may not contain "..".' }
  const extension = path.extname(clean).toLowerCase()
  if (FORBIDDEN_EXTENSIONS.includes(extension)) {
    return {
      ok: false,
      reason: 'A html tool has no build step, so ' + extension + ' files cannot be used. ' +
        'Only app/' + (toolName || '<Tool>') + '.html / .css / .js are allowed.'
    }
  }
  if (clean === 'docs/ssot.html') {
    return { ok: false, reason: 'docs/ssot.html is generated by the factory and cannot be edited by a task.' }
  }
  if (allowedToolPaths(toolName).includes(clean)) return { ok: true, path: clean }
  if (/^docs\/[A-Za-z0-9._-]+\.html$/.test(clean)) return { ok: true, path: clean }
  return {
    ok: false,
    reason: 'Only the html tool files are writable: ' + allowedToolPaths(toolName).join(', ') +
      ' and docs/<name>.html. "' + clean + '" is not one of them.'
  }
}

// A planner that still thinks in React or TypeScript paths would create tasks
// that can never run. Every planned file is mapped onto the real contract file
// so the work happens where the tool actually lives.
function coerceContractPath(relativePath, toolName) {
  const name = String(toolName || '').trim()
  if (!name) return ''
  const clean = String(relativePath || '').replace(/\\/g, '/').trim().replace(/^\.?\//, '')
  if (!clean) return ''
  if (checkTargetPath(clean, name).ok) return clean
  const extension = path.extname(clean).toLowerCase()
  const base = path.basename(clean).toLowerCase()
  if (extension === '.css' || extension === '.scss' || extension === '.less') return 'app/' + name + '.css'
  if (extension === '.html' || extension === '.htm' || extension === '.jsx' || extension === '.tsx' || extension === '.vue') {
    if (/^docs\//.test(clean)) return 'docs/' + path.basename(clean).replace(/\.[^.]+$/, '') + '.html'
    if (base === 'index.html') return 'app/' + name + '.js'
    return 'app/' + name + '.html'
  }
  if (extension === '.md' || extension === '.txt') return 'app/' + name + '.js'
  return 'app/' + name + '.js'
}

function firstLineOf(text) {
  const lines = String(text || '').split('\n')
  return String(lines[0] || '').replace(/\r$/, '')
}

function checkStamp(kind, text, problems, label) {
  const first = firstLineOf(text)
  const expectedKind = kind
  const match = first.match(/^(?:<!--|\/\*)\s*([a-z]+)\s+build\s+([^\s*>]+)\s*(?:-->|\*\/)$/)
  if (!match) {
    problems.push({
      level: 'error',
      message: label + ': the first line must be "' + firstLineFor(expectedKind, '<stamp>') + '"'
    })
    return ''
  }
  if (match[1] !== expectedKind) {
    problems.push({ level: 'error', message: label + ': the build comment says "' + match[1] + ' build" but this is a .' + expectedKind + ' file.' })
  }
  if (!STAMP_PATTERN.test(match[2])) {
    problems.push({ level: 'error', message: label + ': the build stamp "' + match[2] + '" is not YYYY-MM-DD-N.' })
  }
  return match[2]
}

function checkHtml(text, problems, label) {
  FORBIDDEN_HTML.forEach(({ pattern, message }) => {
    if (pattern.test(text)) problems.push({ level: 'error', message: label + ': ' + message })
  })
  if (!/data-tool-build\s*=/.test(text)) {
    problems.push({ level: 'error', message: label + ': the markup must contain a data-tool-build="<stamp>" attribute.' })
  }
  if (/https?:\/\//i.test(text)) {
    problems.push({ level: 'error', message: label + ': no external url (CDN, font, image host) is allowed.' })
  }
}

function checkCss(text, problems, label) {
  if (/<style\b/i.test(text) || /<\/style\s*>/i.test(text)) {
    problems.push({ level: 'error', message: label + ': the css file must not contain style tags.' })
  }
  if (/@import\s+url\(\s*['"]?https?:/i.test(text)) {
    problems.push({ level: 'error', message: label + ': no remote @import is allowed.' })
  }
  if (/url\(\s*['"]?http/i.test(text)) {
    problems.push({ level: 'error', message: label + ': no remote asset url is allowed.' })
  }
}

function checkJs(text, problems, label, stamp) {
  FORBIDDEN_JS_APIS.forEach(({ pattern, message }) => {
    if (pattern.test(text)) problems.push({ level: 'error', message: label + ': ' + message })
  })
  if (!/\bTOOL_BUILD\b/.test(text)) {
    problems.push({ level: 'error', message: label + ': the build number must be declared as var TOOL_BUILD = \'' + (stamp || '<stamp>') + '\'.' })
  }
  if (!/\[TOOL:BOOT\]/.test(text)) {
    problems.push({ level: 'error', message: label + ': the boot log console.log(\'[TOOL:BOOT] build ...\') is missing.' })
  }
  if (!/tool\.onReady\s*\(/.test(text)) {
    problems.push({ level: 'error', message: label + ': the entry point tool.onReady(function (value) { ... }) is missing.' })
  }
  if (!/declareParams/.test(text)) {
    problems.push({ level: 'warn', message: label + ': no tool.declareParams call found. Declare the parameters the tool needs.' })
  }
  if (!/reportMissingParams/.test(text)) {
    problems.push({ level: 'warn', message: label + ': no tool.reportMissingParams call found. Report missing parameters instead of running half configured.' })
  }
}

// Validates one contract file. Returns { ok, problems, stamp }.
function validateContractFile(relativePath, text) {
  const clean = String(relativePath || '').replace(/\\/g, '/')
  const label = path.basename(clean) || clean
  const problems = []
  const extension = path.extname(clean).toLowerCase()
  if (extension === '.html' && !/^app\/test-harness\.html$/.test(clean)) {
    const stamp = checkStamp('html', text, problems, label)
    checkHtml(text, problems, label)
    return { ok: problems.every((problem) => problem.level !== 'error'), problems, stamp }
  }
  if (extension === '.css') {
    const stamp = checkStamp('css', text, problems, label)
    checkCss(text, problems, label)
    return { ok: problems.every((problem) => problem.level !== 'error'), problems, stamp }
  }
  if (extension === '.js') {
    const stamp = checkStamp('js', text, problems, label)
    checkJs(text, problems, label, stamp)
    return { ok: problems.every((problem) => problem.level !== 'error'), problems, stamp }
  }
  return { ok: true, problems, stamp: '' }
}

module.exports = {
  STAMP_PATTERN,
  FORBIDDEN_EXTENSIONS,
  todayStamp,
  buildStamp,
  firstLineFor,
  stampOf,
  allowedToolPaths,
  checkTargetPath,
  coerceContractPath,
  validateContractFile
}
