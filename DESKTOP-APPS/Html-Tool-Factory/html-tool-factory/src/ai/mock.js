'use strict'

// Deterministic stand-in for a real model. It reads machine markers that the
// prompt builders always include, so the whole pipeline (patch, validation,
// tests, iteration loop) can be exercised end to end with zero network calls
// and zero tokens.

const { parseJsonLoose } = require('./parse')

function readMarker(promptText, markerName) {
  const pattern = new RegExp('@@' + markerName + ':([^@]*)@@')
  const match = String(promptText || '').match(pattern)
  return match ? match[1].trim() : ''
}

function ideaNameFrom(promptText) {
  return readMarker(promptText, 'IDEA') || 'Sample Application'
}

function fileContentFor(filePath) {
  const lowerPath = String(filePath || '').toLowerCase()
  const baseName = lowerPath.split('/').pop() || 'file.txt'
  if (lowerPath.endsWith('.html')) {
    return [
      '<!DOCTYPE html>',
      '<html lang="en">',
      '<head>',
      '  <meta charset="utf-8">',
      '  <meta name="viewport" content="width=device-width, initial-scale=1">',
      '  <title>' + baseName + '</title>',
      '  <link rel="stylesheet" href="app.css">',
      '</head>',
      '<body>',
      '  <main class="app-shell">',
      '    <h1>Dry run application</h1>',
      '    <p>Generated by the mock provider.</p>',
      '  </main>',
      '  <script src="app.js"></script>',
      '</body>',
      '</html>',
      ''
    ].join('\n')
  }
  if (lowerPath.endsWith('.js') || lowerPath.endsWith('.cjs')) {
    return [
      "'use strict'",
      '',
      '// Generated by the mock provider for ' + baseName + '.',
      'function describeApplication() {',
      "  return 'dry run'",
      '}',
      '',
      'if (typeof module !== \'undefined\' && module.exports) {',
      '  module.exports = { describeApplication }',
      '}',
      ''
    ].join('\n')
  }
  if (lowerPath.endsWith('.css')) {
    return [
      ':root {',
      '  --ink: #1e293b;',
      '  --paper: #ffffff;',
      '  --line: #e2e8f0;',
      '}',
      '',
      'body {',
      '  margin: 0;',
      '  font-family: system-ui, sans-serif;',
      '  color: var(--ink);',
      '  background: var(--paper);',
      '}',
      '',
      '.app-shell {',
      '  max-width: 960px;',
      '  margin: 0 auto;',
      '  padding: 32px 20px;',
      '}',
      ''
    ].join('\n')
  }
  if (lowerPath.endsWith('.json')) {
    return JSON.stringify({ generatedBy: 'mock', file: baseName }, null, 2) + '\n'
  }
  return '# ' + baseName + '\n\nGenerated by the mock provider.\n'
}

function planTasksAnswer(promptText) {
  const iteration = Number(readMarker(promptText, 'ITERATION') || 1)
  const toolName = readMarker(promptText, 'TOOLNAME') || 'TheTool'
  const failedTests = readMarker(promptText, 'FAILED_TESTS')
  if (failedTests) {
    return {
      tasks: [
        {
          title: 'Fix failing check: ' + failedTests.slice(0, 60),
          kind: 'code',
          files: ['app/' + toolName + '.js'],
          acceptance: ['The failing check passes again']
        }
      ],
      notes: 'Mock: repair task driven by the failed check marker.'
    }
  }
  const baseTasks = [
    {
      title: 'Wire the main screen of the tool',
      kind: 'code',
      files: ['app/' + toolName + '.html', 'app/' + toolName + '.css'],
      acceptance: ['The main screen renders with the tool class prefix', 'Every selector stays scoped to the tool root']
    },
    {
      title: 'Add the saved state to the tool logic',
      kind: 'code',
      files: ['app/' + toolName + '.js'],
      acceptance: ['app/' + toolName + '.js parses with node --check']
    }
  ]
  if (iteration > 1) {
    baseTasks.push({
      title: 'Write the iteration ' + iteration + ' build note',
      kind: 'doc',
      files: ['docs/build-notes.md'],
      acceptance: ['The note file exists']
    })
  }
  return { tasks: baseTasks, notes: 'Mock plan for iteration ' + iteration + '.' }
}

function riskReviewAnswer(promptText) {
  const questionCount = Number(readMarker(promptText, 'QUESTION_COUNT') || 0)
  const questions = []
  if (questionCount === 0) {
    questions.push({
      text: 'Who is allowed to change the data?',
      assumption: 'Only signed-in owners can change their own records.',
      recommendedAnswer: 'Authenticated owners only; deny by default.'
    })
    questions.push({
      text: 'Where does sensitive data live?',
      assumption: 'No secrets in code or client bundle.',
      recommendedAnswer: 'Server-side only, never in the client.'
    })
  }
  return {
    risks: [
      {
        severity: 'high',
        text: 'Access control is not specified',
        mitigation: 'Deny by default and check ownership on every write'
      },
      {
        severity: 'medium',
        text: 'No input validation at the boundary',
        mitigation: 'Validate and trim every field before storing it'
      }
    ],
    questions,
    notes: 'Mock risk review.'
  }
}

function resolveRisksAnswer(promptText) {
  const questionIds = readMarker(promptText, 'QUESTIONS').split('|').filter(Boolean)
  return {
    answers: questionIds.map((questionId) => ({
      questionId,
      answer: 'Answered with the safer default: deny by default, validate input, keep secrets server side.'
    })),
    decisions: [
      {
        text: 'Deny by default and validate every input at the boundary',
        rationale: 'Cheapest rule that removes a whole class of security problems.'
      }
    ],
    riskActions: [],
    tasks: []
  }
}

function appendContentFor(filePath, taskId) {
  const lowerPath = String(filePath || '').toLowerCase()
  if (lowerPath.endsWith('.css')) return '\n/* mock revision for ' + taskId + ' */\n'
  if (lowerPath.endsWith('.html')) return '\n<!-- mock revision for ' + taskId + ' -->\n'
  if (lowerPath.endsWith('.md')) return '\nMock revision for ' + taskId + '.\n'
  return '\n// mock revision for ' + taskId + '\n'
}

function applyTaskAnswer(promptText) {
  const fileList = readMarker(promptText, 'FILES').split('|').map((item) => item.trim()).filter(Boolean)
  const existingList = readMarker(promptText, 'EXISTS').split('|').map((item) => item.trim()).filter(Boolean)
  const taskId = readMarker(promptText, 'TASK')
  const ops = fileList.map((filePath) => {
    const alreadyExists = existingList.includes(filePath)
    if (alreadyExists) {
      return {
        op: 'append',
        file: filePath,
        content: appendContentFor(filePath, taskId)
      }
    }
    return { op: 'create', file: filePath, content: fileContentFor(filePath) }
  })
  return {
    summary: 'Mock implementation for ' + taskId + ' (' + fileList.length + ' file(s)).',
    ops,
    notes: ''
  }
}

